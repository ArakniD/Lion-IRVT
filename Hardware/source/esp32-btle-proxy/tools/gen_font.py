HEADER = """/*
 * ui_font.c
 *
 * 5x7 font table. See ui_font.h for the cell layout.
 *
 * GENERATED by tools/gen_font.py - edit the glyph data there, not here.
 *
 * Only printable ASCII is covered, which is all the UI emits: state
 * letters, digits, units and field labels.
 */

#include "ui_font.h"

#define FONT_FIRST  0x20
#define FONT_LAST   0x7E

static const uint8_t k_font[FONT_LAST - FONT_FIRST + 1][FONT_W] = {
"""

FOOTER = """};

static const uint8_t k_blank[FONT_W] = {0, 0, 0, 0, 0};

const uint8_t *ui_font_glyph(char c)
{
    const unsigned char u = (unsigned char)c;
    if (u < FONT_FIRST || u > FONT_LAST) {
        return k_blank;
    }
    return k_font[u - FONT_FIRST];
}
"""


def main():
    rows = []
    missing = []
    for code in range(0x20, 0x7F):
        ch = chr(code)
        if ch not in F:
            missing.append(ch)
        g = F.get(ch, (0, 0, 0, 0, 0))
        # Render the comment safely: backslash and the comment terminator
        # would otherwise break the C file.
        note = 'backslash' if ch == chr(92) else ch
        rows.append("    {0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X},  /* %s */"
                    % (g[0], g[1], g[2], g[3], g[4], note))

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "..", "components", "display", "ui_font.c")
    with io.open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER + "\n".join(rows) + "\n" + FOOTER)

    print("wrote %s (%d glyphs)" % (os.path.normpath(out), len(rows)))
    if missing:
        print("WARNING: no glyph data for: %r" % missing)


if __name__ == "__main__":
    main()
